export function profileHeight(phi, profile = SEGMENT_PROFILE) {
  if(phi<=profile[0][0])return profile[0][1];
  for(let i=1;i<profile.length;i++)if(phi<=profile[i][0]){
    const [a,y]=profile[i-1],[b,z]=profile[i],t=(phi-a)/(b-a);
    return y+(z-y)*t*t*(3-2*t);
  }
  return profile[profile.length-1][1];
}
export const profileRange = (profile=SEGMENT_PROFILE) => [profile[0][0]-8*Math.PI/180,profile[profile.length-1][0]+8*Math.PI/180];

// Lift-off contour of selector102: the outer face of its slotted wall, as
// [local azimuth, radius] in the segment's own frame. 134's follower shoulder
// (the root of its pin) bears on it. Between click-stops the wall stands proud and
// holds134 swung out, so the idler is off the pulley and the drive wall while the
// slot moves it vertically ("abgehoben ... verschoben", 1219 manual p.4; 1229
// manual p.4/Fig. 2). At each click-stop the wall is recessed and spring-loaded134
// wedges the idler in. Mechanism: manual text. Shape and every number: estimate.
// Recess centres are where134's shoulder stands with the idler wedged at the
// nominal detent (computed once from this model, not regenerated); the proud
// radius holds the idler axle near the photo-measured disengaged centre
// (DECISIONS D8, (-61, +70) mm).
export const LIFT_OFF = Object.freeze({
  recesses: Object.freeze([0.4435, 0.9773, 1.4970]),
  floor: 0.0088,  // m, recess radius: below every engaged shoulder radius (9.26 mm least)
  proud: 0.0121,  // m, between stops: holds134 just inside its rest stop (shoulder r 12.17 mm there)
  flat: 0.01,     // rad, half-width of the recess floor
  flank: 0.16,     // rad, width of each flank: keeps the push on134 under 0.5 m/s at the axle for a 0.4 s 33 <-> 78 sweep
  range: Object.freeze([0.20, 1.75]),
});
export function liftOffRadius(phi, c = LIFT_OFF) {
  let r = c.proud;
  for (const centre of c.recesses) {
    const d = Math.abs(phi - centre);
    if (d >= c.flat + c.flank) continue;
    const t = d <= c.flat ? 0 : (d - c.flat) / c.flank, s = t * t * (3 - 2 * t);
    r = Math.min(r, c.floor + (c.proud - c.floor) * s);
  }
  return r;
}
